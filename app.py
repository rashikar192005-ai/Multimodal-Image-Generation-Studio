
import streamlit as st
from PIL import Image, ImageDraw
from io import BytesIO
import random

st.set_page_config(
    page_title="Multimodal Image Generation Studio",
    page_icon="🎨",
    layout="centered"
)

st.title("🎨 Multimodal Image Generation Studio")
st.write("Create and download a sample digital artwork.")

st.info(
    "Offline Demo Mode: Create a sample illustration "
    "without an external API or paid credits."
)

prompt = st.text_area(
    "Describe your image",
    value="A cute panda sitting in a magical forest"
)

resolution = st.selectbox(
    "Image Resolution",
    ["512x512", "768x768", "1024x1024"]
)

count = st.slider("Number of Images", 1, 2, 1)


def create_sample_art(width, height, seed):
    random.seed(seed)
    img = Image.new("RGB", (width, height), "#b8e6ff")
    draw = ImageDraw.Draw(img)

    # Sky and glowing sun
    draw.ellipse(
        (width * .72, height * .08,
         width * .88, height * .24),
        fill="#ffe58a"
    )

    # Distant forest
    for i in range(9):
        x = i * width // 8
        draw.polygon(
            [(x, height * .55),
             (x + width * .09, height * .22),
             (x + width * .18, height * .55)],
            fill="#72bd83"
        )

    # Ground
    draw.rectangle(
        (0, int(height * .55), width, height),
        fill="#65b96e"
    )

    # Trees
    for x in [width * .08, width * .83, width * .92]:
        draw.rectangle(
            (int(x), int(height * .35),
             int(x + width * .035), int(height * .72)),
            fill="#805438"
        )
        draw.ellipse(
            (int(x - width * .07), int(height * .25),
             int(x + width * .12), int(height * .47)),
            fill="#25804b"
        )

    # Panda ears
    cx = width // 2
    cy = int(height * .55)
    r = int(width * .105)

    draw.ellipse(
        (cx - r - r // 2, cy - r,
         cx - r // 3, cy + r // 2),
        fill="#20252c"
    )
    draw.ellipse(
        (cx + r // 3, cy - r,
         cx + r + r // 2, cy + r // 2),
        fill="#20252c"
    )

    # Panda face
    draw.ellipse(
        (cx - r, cy - r // 2,
         cx + r, cy + r * 1.5),
        fill="#fffaf0",
        outline="#30343b",
        width=max(2, width // 180)
    )

    # Eye patches
    patch = int(r * .37)
    draw.ellipse(
        (cx - patch * 2, cy, cx - patch // 2, cy + patch * 2),
        fill="#252a32"
    )
    draw.ellipse(
        (cx + patch // 2, cy, cx + patch * 2, cy + patch * 2),
        fill="#252a32"
    )

    # Eyes
    eye = max(3, width // 100)
    draw.ellipse(
        (cx - patch, cy + patch // 2,
         cx - patch + eye, cy + patch // 2 + eye),
        fill="white"
    )
    draw.ellipse(
        (cx + patch, cy + patch // 2,
         cx + patch + eye, cy + patch // 2 + eye),
        fill="white"
    )

    # Nose and body
    nr = max(4, width // 45)
    draw.ellipse(
        (cx - nr, cy + r // 2,
         cx + nr, cy + r // 2 + nr),
        fill="#252a32"
    )
    draw.ellipse(
        (cx - int(r * 1.15), cy + r,
         cx + int(r * 1.15), cy + r * 3),
        fill="#fffaf0",
        outline="#30343b",
        width=max(2, width // 180)
    )

    # Flowers
    for _ in range(20):
        x = random.randint(10, width - 10)
        y = random.randint(int(height * .75), height - 10)
        fr = max(3, width // 100)
        draw.ellipse(
            (x - fr, y - fr, x + fr, y + fr),
            fill=random.choice(
                ["#ff8eb3", "#fff1a6", "#d7b5ff"]
            )
        )

    return img


if st.button("✨ Generate Sample Artwork", type="primary"):
    if not prompt.strip():
        st.warning("Please enter an image description.")
    else:
        w, h = map(int, resolution.split("x"))

        for i in range(count):
            artwork = create_sample_art(w, h, i + 10)

            st.success(f"Sample artwork {i + 1} is ready!")
            st.image(
                artwork,
                caption="Offline Demo Illustration — Panda in a Forest",
                use_container_width=True
            )

            buffer = BytesIO()
            artwork.save(buffer, format="PNG")

            st.download_button(
                "⬇️ Download Sample Artwork",
                data=buffer.getvalue(),
                file_name=f"sample_artwork_{i + 1}.png",
                mime="image/png",
                key=f"download_{i}"
            )

        st.caption(
            "Demo note: This is a locally drawn sample illustration, "
            "not an image generated by an AI model."
        )

st.divider()
st.subheader("Project Features")
st.write("✅ Text prompt input")
st.write("✅ Image resolution selection")
st.write("✅ Multiple sample images")
st.write("✅ Image preview and PNG download")
st.write("✅ Offline operation without API credits")

st.divider()
st.caption("Multimodal Image Generation Studio | Project Demo")
